using Godot;

namespace PlantsVsZombies.Collision;

/// <summary>
/// 判定层面对的箱子。
///
/// **这是下一代。** 游戏里现有一个同名接口（`MainGame/HitBox/` 下），它管的是
/// 一个静态矩形 + 两个区域事件 + 一份重叠列表，也就是引擎那一套。两者是同一个
/// 角色的两代，**不是并存的两个东西**：接入时删掉旧的那个，名字直接接上，
/// 引用点不用再改第二遍——同名就是为这个留的。
///
/// 并存期间不会歧义：没有任何文件同时 using 两边。真出现同时用到的场合，
/// C# 会报 ambiguous，那时的正解是删旧的，不是给这个改名。
///
/// **判定方只认这个接口**——箱子底下是什么（Area2D、别的节点、纯数据对象）一概
/// 不知道，也不该知道。要让这条约束有牙，判定侧就不许出现 `is 某个具体实现`
/// 这类向下转型，否则接口白抽象。
///
/// 几何是**问出来的**（下面那两个成员），不是存在字段里的：原版的几何每帧现算，
/// 同一帧内问两次可以拿到两个不同的值。
/// </summary>
public interface IHitBox
{
	/// <summary>当前有几个形状。多数实体是 1，组合形状时才更多</summary>
	int ShapeCount { get; }

	/// <summary>
	/// 取第 index 个形状（世界坐标，整数）。
	///
	/// 用"个数 + 按下标取"而不是"返回一个列表"，是为了判定路径上零分配——
	/// 判定跑在每物理帧的热循环里。
	/// </summary>
	HitShape GetShape(int index);

	/// <summary>
	/// 这个箱子现在参不参与判定。
	///
	/// **怎么落实是实现自己的事**：走引擎的箱子改的是 Area2D 属性、只能延迟生效；
	/// 纯数据的箱子就是个普通字段，设了立刻读到。判定方只读值，不关心它是怎么
	/// 变成这个值的——那个一帧延迟因此是实现选择的代价，不是判定层的负担。
	/// </summary>
	bool Monitorable { get; set; }

	/// <summary>箱子的世界位置。给需要粗筛的调用方用（浮点，不是判定几何）</summary>
	Vector2 GlobalPosition { get; }

	/// <summary>箱子挂在谁身上。结算伤害时靠它拿到实体</summary>
	Node AttachedNode { get; set; }
}

/// <summary>
/// 参与判定的一侧。调度只需要知道"它的箱子是哪个"。
///
/// 用接口而不是 `Func` 委托：委托要调用方每次传一个，
/// 捕获变量的写法会在每帧的热循环里分配；接口约束则是零分配，且签名字面上就
/// 说明了"这是个可判定的东西"。
/// </summary>
public interface IHittable
{
	IHitBox HitBox { get; }
}
